
X = int(input("Ingresa el primer número: "))
Y = int(input("Ingresa el segundo número: "))
M=  int(input("que operacion quiere hacer digite 1=suma, 2=resta,3=multiplicacion"))
if M==1:
    resultado1 = X+Y
    print(f"La suma es: {resultado1}")
if M==2:
    resultado = X-Y
    print(f"La RESTA es: {resultado}")
if M==3:
    resultado = X*Y
    print(f"La MULTIPLICACION  es: {resultado}")



